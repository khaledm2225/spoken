import SwiftUI

extension Color {
    /// Creates a colour from a 24 bit RGB hex literal, for example `0x6C5CE0`.
    init(hex: UInt32) {
        self.init(
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255
        )
    }
}
